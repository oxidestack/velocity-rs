#!/usr/bin/env python3
"""Generates src/jj_scan.rs: the look-ahead scanners (`jj_3_N`, `jj_3R_*`), the `jj_la1_*` expected-token masks, the
token kind constants and `tokenImage` of Velocity 2.4.1's JavaCC parser.

The parser is generated from the pinned upstream grammar with the JavaCC version Velocity's build uses
(javacc-maven-plugin 3.1.0 -> JavaCC 7.0.13): jjtree, then javacc, with the pom's grammar properties substituted.
The tables were checked against the compiled parser in velocity-engine-core-2.4.1.jar by reflection (jj_la1_0..2 equal,
24 `jj_3_N` and 127 `jj_3R_*` methods). Run from the repository root: python3 generators/gen_jj_scan.py
Regenerating reproduces the committed file byte for byte."""
import hashlib, os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JAVACC = "https://repo.maven.apache.org/maven2/net/java/dev/javacc/javacc/7.0.13/javacc-7.0.13.jar"
CACHE = os.path.join(ROOT, "generators/target")
GRAMMAR = os.path.join(ROOT, "upstream/velocity-engine-core/src/main/parser/Parser.jjt")
SUBST = {"parser.basename": "Standard", "parser.package": "org.apache.velocity.runtime.parser", "parser.char.dollar": "$",
         "parser.char.hash": "#", "parser.char.at": "@", "parser.char.asterisk": "*"}


def javacc_jar():
    os.makedirs(CACHE, exist_ok=True)
    jar = os.path.join(CACHE, "javacc-7.0.13.jar")
    if not os.path.exists(jar):
        subprocess.run(["curl", "-sSfL", "-o", jar, JAVACC], check=True)
        sha1 = subprocess.run(["curl", "-sSfL", JAVACC + ".sha1"], check=True, stdout=subprocess.PIPE).stdout.decode().split()[0]
        if hashlib.sha1(open(jar, "rb").read()).hexdigest() != sha1:
            os.remove(jar)
            sys.exit("javacc jar checksum mismatch")
    return jar


def generate_java(tmp):
    jar = javacc_jar()
    text = open(GRAMMAR).read()
    for k, v in SUBST.items():
        text = text.replace("${%s}" % k, v)
    open(os.path.join(tmp, "Parser.jjt"), "w").write(text)
    run = lambda *a: subprocess.run(a, cwd=tmp, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    run("java", "-cp", jar, "jjtree", "-NODE_PACKAGE=org.apache.velocity.runtime.parser.node", "-MULTI=true", "-NODE_USES_PARSER=true", "-STATIC=false", "Parser.jjt")
    run("java", "-cp", jar, "javacc", "-STATIC=false", "-TOKEN_MANAGER_USES_PARSER=true", "-BUILD_NODE_FILES=false", "Parser.jj")
    return open(os.path.join(tmp, "StandardParser.java")).read(), open(os.path.join(tmp, "StandardParserConstants.java")).read()


NAMES = {}


def konst(k):
    if k.isdigit():
        return NAMES[int(k)]
    return k


def main():
    with tempfile.TemporaryDirectory() as tmp:
        java, consts = generate_java(tmp)
    # token kinds and images
    for name, val in re.findall(r"int (\w+) = (\d+);", consts.split("tokenImage")[0].split("int DEFAULT")[0]):
        NAMES.setdefault(int(val), name)
    kinds = [(n, int(v)) for n, v in re.findall(r"int (\w+) = (\d+);", consts.split("/** Lexical state.")[0])]
    images = re.search(r"tokenImage = \{(.*?)\n  \};", consts, re.S).group(1)
    images = [i.strip().rstrip(",") for i in images.strip().split("\n")]
    assert len(images) == 81
    # tables
    tables = {}
    for n in (0, 1, 2):
        body = re.search(r"jj_la1_%d = new int\[\] \{(.*?)\};" % n, java).group(1)
        tables[n] = [int(x, 16) for x in body.split(",") if x.strip()]
        assert len(tables[n]) == 107
    # scanners: from the first jj_2_N definition on to the first of jj_la1 tables
    start = java.index("private boolean jj_2_1(")
    end = java.index("private void jj_la1_init_0") if "private void jj_la1_init_0" in java else java.index("static private int[] jj_la1_0")
    region = java[start:end]
    scanners = [(m.group(1), m.group(2)) for m in re.finditer(r"private boolean (jj_3\w+)\(\)\n \{\n(.*?)\n  \}\n", region, re.S)]
    assert len(scanners) == 24 + 127, len(scanners)
    out = []
    out.append("// @generated by generators/gen_jj_scan.py from upstream/velocity-engine-core/src/main/parser/Parser.jjt")
    out.append("// (JavaCC 7.0.13, as Velocity 2.4.1's build generates it). Do not edit.")
    out.append("//! JavaCC's look-ahead scanners (`jj_3_N`, `jj_3R_*`) and expected-token tables of Velocity's parser, used by")
    out.append("//! [`crate::jj`] to rebuild the `ParseException` the generated parser would have thrown.")
    out.append("")
    out.append("#![allow(non_snake_case, unused_mut, dead_code, clippy::all)]")
    out.append("")
    out.append("use crate::jj::{Jj, Res};")
    out.append("")
    for name, val in kinds:
        out.append("pub const %s: u8 = %d;" % (name, val))
    out.append("")
    out.append("/// `StandardParserConstants.tokenImage`.")
    out.append("pub const TOKEN_IMAGE: [&str; %d] = [" % len(images))
    for i in images:
        out.append("    %s," % java_string_to_rust(i))
    out.append("];")
    out.append("")
    for n in (0, 1, 2):
        out.append("pub const LA1_%d: [u32; 107] = [%s];" % (n, ", ".join("0x%x" % x for x in tables[n])))
    out.append("")
    out.append("/// `jj_3_N` for the look-ahead `jj_2_N` (1-based).")
    out.append("pub const LOOKAHEADS: usize = 24;")
    out.append("")
    out.append("impl Jj<'_> {")
    out.append("    pub(crate) fn jj_3(&mut self, n: usize) -> Res {")
    out.append("        match n {")
    for i in range(1, 25):
        out.append("            %d => self.jj_3_%d()," % (i, i))
    out.append("            _ => unreachable!(),")
    out.append("        }")
    out.append("    }")
    out.append("")
    for name, body in scanners:
        out.extend(render_scanner(name, body))
        out.append("")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


def java_string_to_rust(j):
    # Java literal like "\"\\u001c\"" or <EOF> -> Rust literal with the same characters.
    inner = j[1:-1]
    chars, i = [], 0
    while i < len(inner):
        c = inner[i]
        if c == "\\":
            n = inner[i + 1]
            if n == "u":
                chars.append(chr(int(inner[i + 2:i + 6], 16)))
                i += 6
                continue
            chars.append({"\\": "\\", '"': '"', "n": "\n", "t": "\t"}[n])
            i += 2
            continue
        chars.append(c)
        i += 1
    s = "".join(chars)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\x1c", "\\u{1c}") + '"'


def render_scanner(name, body):
    lines = [l.strip() for l in body.split("\n") if l.strip() and l.strip() != "{"]
    out = ["    pub(crate) fn %s(&mut self) -> Res {" % name]
    depth = 2
    pad = lambda: "    " * depth
    for s in lines:
        if s == "Token xsp;":
            out.append(pad() + "let mut xsp: isize;")
        elif s == "xsp = jj_scanpos;":
            out.append(pad() + "xsp = self.scanpos;")
        elif s == "jj_scanpos = xsp;":
            out.append(pad() + "self.scanpos = xsp;")
        elif s == "while (true) {":
            out.append(pad() + "loop {")
            depth += 1
        elif s == "jj_lookingAhead = true;":
            out.append(pad() + "self.looking_ahead = true;")
        elif s == "jj_lookingAhead = false;":
            out.append(pad() + "self.looking_ahead = false;")
        elif s == "jj_semLA = !isRightParenthesis();":
            out.append(pad() + "self.sem_la = !self.is_right_parenthesis()?;")
        elif s.startswith("if (!jj_semLA || "):
            callee = re.search(r"(jj_3R_\w+)\(\)", s).group(1)
            out.append(pad() + "if !self.sem_la || self.%s()? {" % callee)
            out.append(pad() + "    return Ok(true);")
            out.append(pad() + "}")
        elif s == "return false;":
            out.append(pad() + "Ok(false)")
        elif s == "return true;":
            out.append(pad() + "Ok(true)")
        elif s == "}":
            depth -= 1
            out.append(pad() + "}")
        else:
            m = re.fullmatch(r"if \((jj_3\w+)\(\)\) return true;", s)
            if m:
                out += [pad() + "if self.%s()? {" % m.group(1), pad() + "    return Ok(true);", pad() + "}"]
                continue
            m = re.fullmatch(r"if \(jj_scan_token\((\w+)\)\) return true;", s)
            if m:
                out += [pad() + "if self.scan_token(%s)? {" % konst(m.group(1)), pad() + "    return Ok(true);", pad() + "}"]
                continue
            m = re.fullmatch(r"if \((jj_3\w+)\(\)\) jj_scanpos = xsp;", s)
            if m:
                out += [pad() + "if self.%s()? {" % m.group(1), pad() + "    self.scanpos = xsp;", pad() + "}"]
                continue
            m = re.fullmatch(r"if \(jj_scan_token\((\w+)\)\) jj_scanpos = xsp;", s)
            if m:
                out += [pad() + "if self.scan_token(%s)? {" % konst(m.group(1)), pad() + "    self.scanpos = xsp;", pad() + "}"]
                continue
            m = re.fullmatch(r"if \((jj_3\w+)\(\)\) \{", s)
            if m:
                out.append(pad() + "if self.%s()? {" % m.group(1))
                depth += 1
                continue
            m = re.fullmatch(r"if \(jj_scan_token\((\w+)\)\) \{", s)
            if m:
                out.append(pad() + "if self.scan_token(%s)? {" % konst(m.group(1)))
                depth += 1
                continue
            m = re.fullmatch(r"if \((jj_3\w+)\(\)\) \{ jj_scanpos = xsp; break; \}", s)
            if m:
                out += [pad() + "if self.%s()? {" % m.group(1), pad() + "    self.scanpos = xsp;", pad() + "    break;", pad() + "}"]
                continue
            sys.exit("unconverted scanner line: " + s)
    out.append("    }")
    return out


main()
